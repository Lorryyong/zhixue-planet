/** 关键词命中课本册次；命中不到返回 ''（交由人工补充） */
function inferBook(name, subject, grade) {
  const s = String(name || '').trim()
  if (!s) return ''
  for (let i = 0; i < RULES.length; i++) {
    const keys = RULES[i].kw
    for (let j = 0; j < keys.length; j++) {
      if (s.indexOf(keys[j]) >= 0) return RULES[i].book
    }
  }
  return ''
}

/**
 * 由知识点标签构建结构化「知识点 → 课本册次」数组。
 * @param {string[]} tags 知识点名称数组（knowledge_tags）
 * @param {Array} explicit 已保存的 [{name, book}]（优先）
 * @returns {Array<{name:string, book:string, inferred:boolean}>}
 */
function buildKnowledgePoints(tags, explicit, subject, grade) {
  let arr = []
  if (Array.isArray(explicit) && explicit.length) {
    arr = explicit.map(function (x) {
      if (typeof x === 'string') return { name: x, book: '' }
      return { name: String((x && x.name) || ''), book: String((x && x.book) || '') }
    })
  } else {
    arr = (Array.isArray(tags) ? tags : []).map(function (t) { return { name: String(t || ''), book: '' } })
  }
  return arr.filter(function (x) { return !!x.name }).slice(0, 8).map(function (x) {
    const auto = x.book ? '' : inferBook(x.name, subject, grade)
    return {
      name: x.name.slice(0, 40),
      book: (x.book || auto || '').slice(0, 30),
      inferred: !x.book && !!auto
    }
  })
}

